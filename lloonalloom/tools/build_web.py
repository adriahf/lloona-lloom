"""Bundle the editable UI into PROGMEM; Arduino IDE needs no build plugin."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]


def build():
    html = (ROOT / 'web/index.html').read_text(encoding='utf-8')
    for marker, path in [('STYLE', 'style.css'), ('CORE', 'core.js'), ('APP', 'app.js')]:
        content = (ROOT / 'web' / path).read_text(encoding='utf-8')
        if marker == 'STYLE':
            content = re.sub(r'\s+', ' ', content)
            content = re.sub(r'\s*([{};])\s*', r'\1', content)
        html = html.replace(f'/* INLINE_{marker} */', content)
    assert ')====="' not in html
    return ('// Generated by tools/build_web.py. Edit web/ instead.\n'
            '#ifndef WEBPAGE_H\n#define WEBPAGE_H\n#include <Arduino.h>\n'
            'const char INDEX_HTML[] PROGMEM = R"=====(\n' + html + '\n)=====";\n#endif\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = build()
    path = ROOT / 'webpage.h'
    if args.check:
        if path.read_text(encoding='utf-8') != output:
            raise SystemExit('webpage.h is out of date; run python tools/build_web.py')
        print('webpage.h matches web/ sources')
    else:
        path.write_text(output, encoding='utf-8', newline='\n')
        print(f'webpage.h: {len(output.encode("utf-8")):,} bytes')
